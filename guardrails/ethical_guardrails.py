"""Guardrail 9 – Ethical & Compliance · bias · EEO · fairness · audit trail · explainability"""
import re, uuid, logging
from datetime import datetime, timezone
from typing import Dict, List, Optional, Tuple
from config.settings import get_settings

log = logging.getLogger("guard.ethical")
cfg = get_settings()

GENDER_BIAS_RE  = [re.compile(p, re.I) for p in [
    r"this\s+role\s+(is\s+)?better\s+suited\s+for\s+(men|women)",
    r"\b(male|female)\s+candidates\s+(should|must|are)\b",
]]
AGE_BIAS_RE     = [re.compile(p, re.I) for p in [
    r"\b(too\s+old|too\s+young)\s+for", r"\bdigital\s+native\s+required\b",
]]
EEO_ILLEGAL_RE  = [re.compile(p, re.I) for p in [
    r"(do\s+you\s+plan\s+to\s+have\s+children)",
    r"(what\s+is\s+your\s+religion)",
    r"(how\s+old\s+are\s+you)",
    r"(are\s+you\s+(married|single|divorced))",
    r"(do\s+you\s+have\s+any\s+disabilities)",
]]
PROTECTED = ["race","ethnicity","religion","gender","age","disability",
             "national origin","marital status","pregnancy"]
DISCLAIMER = ("\n\n---\n*AI Disclosure: This content is generated by IBM Granite "
              "for interview preparation purposes only. It does not guarantee job placement.*")

_audit: List[Dict] = []


def check(content: str, content_type: str = "question",
          user_id: str = "anon", session_id: str = "") -> Dict:
    bias, compliance, recs = [], [], []

    if cfg.bias_detection:
        if any(r.search(content) for r in GENDER_BIAS_RE):
            bias.append("gender_bias"); recs.append("Use gender-neutral language.")
        if any(r.search(content) for r in AGE_BIAS_RE):
            bias.append("age_bias"); recs.append("Focus on skills, not age.")

    for r in EEO_ILLEGAL_RE:
        if r.search(content):
            compliance.append("EEO violation: illegal interview question detected")
            recs.append("Remove questions about protected characteristics.")
            break

    lower = content.lower()
    mentioned = [p for p in PROTECTED if p in lower]
    if mentioned:
        compliance.append(f"Protected characteristics mentioned: {mentioned}")

    fairness = max(0.0, round(1.0 - len(bias) * 0.15 - len(compliance) * 0.2, 3))
    passed = len(bias) == 0 and len(compliance) == 0

    explanation = (
        f"Ethical check ({content_type}): fairness={fairness}. "
        + (f"Bias: {bias}. " if bias else "")
        + (f"Compliance issues: {'; '.join(compliance)}" if compliance else "No issues found.")
    )

    record = {
        "audit_id": str(uuid.uuid4()),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "user_id": user_id,
        "session_id": session_id,
        "content_type": content_type,
        "bias": bias,
        "compliance": compliance,
        "fairness": fairness,
        "passed": passed,
        "explanation": explanation,
        "recommendations": recs,
    }
    if cfg.audit_trail:
        _audit.append(record)
        if len(_audit) > 1000:
            _audit[:] = _audit[-1000:]

    return record


def add_disclaimer(content: str) -> str:
    return content + DISCLAIMER


def bias_report(session_id: str) -> Dict:
    records = [r for r in _audit if r.get("session_id") == session_id]
    if not records:
        return {"session_id": session_id, "checks": 0}
    from collections import Counter
    all_bias = []
    for r in records:
        all_bias.extend(r.get("bias", []))
    return {
        "session_id": session_id, "checks": len(records),
        "bias_counts": dict(Counter(all_bias)),
        "avg_fairness": round(sum(r["fairness"] for r in records) / len(records), 3),
    }
